	public static function capacity_bytes(int $version, int $ec_level): int{
		$info = self::VERSION_TABLE[$version][$ec_level];
		return $info[2] * $info[3] + $info[4] * $info[5];
	}

	public static function char_count_bits(int $mode, int $version): int{
		$group = ($version <= 9) ? 0 : (($version <= 26) ? 1 : 2);
		return self::CHAR_COUNT_BITS[$mode][$group];
	}

	public static function module_count(int $version): int{
		return $version * 4 + 17;
	}
